"""SQLAlchemy models (spec section 7). Scores are 0-100; every claim links to evidence."""
from __future__ import annotations

from datetime import date, datetime
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    Boolean,
    JSON,
    CheckConstraint,
    Date,
    Computed,
    DateTime,
    Index,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    UniqueConstraint,
    false,
    func,
)
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy import event
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

EMBEDDING_DIM = 768


class Base(DeclarativeBase):
    pass


def _now():
    return mapped_column(DateTime(timezone=True), server_default=func.now())


class Instrument(Base):
    __tablename__ = "instruments"
    id: Mapped[int] = mapped_column(primary_key=True)
    isin: Mapped[str] = mapped_column(String(12), unique=True)
    nse_code: Mapped[str | None] = mapped_column(String(32))
    bse_code: Mapped[str | None] = mapped_column(String(32))
    name: Mapped[str] = mapped_column(String(255))
    macro_sector: Mapped[str | None] = mapped_column(String(128))
    sector: Mapped[str | None] = mapped_column(String(128))
    industry: Mapped[str | None] = mapped_column(String(128))
    basic_industry: Mapped[str | None] = mapped_column(String(128))
    classification_status: Mapped[str | None] = mapped_column(String(32))
    status: Mapped[str] = mapped_column(String(32), default="active")
    surveillance_flag: Mapped[str | None] = mapped_column(String(32))
    listing_date: Mapped[date | None] = mapped_column(Date)
    avg_daily_value: Mapped[float | None] = mapped_column(Float)


class Source(Base):
    __tablename__ = "sources"
    __table_args__ = (CheckConstraint("tier BETWEEN 1 AND 3", name="ck_sources_tier"),)
    id: Mapped[int] = mapped_column(primary_key=True)
    url: Mapped[str] = mapped_column(Text)
    type: Mapped[str] = mapped_column(String(64))
    tier: Mapped[int] = mapped_column(Integer)
    publish_date: Mapped[date | None] = mapped_column(Date)
    fetch_date: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    content_hash: Mapped[str | None] = mapped_column(String(128))
    status: Mapped[str] = mapped_column(String(32), default="ok", server_default="ok")


class Document(Base):
    __tablename__ = "documents"
    id: Mapped[int] = mapped_column(primary_key=True)
    source_id: Mapped[int] = mapped_column(ForeignKey("sources.id"))
    instrument_id: Mapped[int | None] = mapped_column(ForeignKey("instruments.id"))
    # set (with instrument_id NULL) on sector-scoped documents; matches Instrument.sector exactly
    sector: Mapped[str | None] = mapped_column(String(128), index=True)
    title: Mapped[str | None] = mapped_column(Text)
    doc_type: Mapped[str | None] = mapped_column(String(64))
    period: Mapped[str | None] = mapped_column(String(32))
    created_at = _now()


class Chunk(Base):
    __tablename__ = "chunks"
    __table_args__ = (
        Index("ix_chunks_text_tsv", "text_tsv", postgresql_using="gin"),
    )
    id: Mapped[int] = mapped_column(primary_key=True)
    document_id: Mapped[int] = mapped_column(ForeignKey("documents.id"))
    source_id: Mapped[int] = mapped_column(ForeignKey("sources.id"))
    ordinal: Mapped[int] = mapped_column(Integer, default=0)
    text: Mapped[str] = mapped_column(Text)
    embedding: Mapped[Any] = mapped_column(Vector(EMBEDDING_DIM), nullable=True)
    # generated by Postgres from `text`; used for full-text search (never written by the app)
    text_tsv: Mapped[Any] = mapped_column(
        TSVECTOR, Computed("to_tsvector('english', text)", persisted=True), nullable=True
    )
    document: Mapped["Document"] = relationship()
    source: Mapped["Source"] = relationship()


class Fact(Base):
    __tablename__ = "facts"
    id: Mapped[int] = mapped_column(primary_key=True)
    instrument_id: Mapped[int] = mapped_column(ForeignKey("instruments.id"))
    source_id: Mapped[int] = mapped_column(ForeignKey("sources.id"))
    metric: Mapped[str] = mapped_column(String(128))
    value: Mapped[float] = mapped_column(Float)
    unit: Mapped[str | None] = mapped_column(String(32))
    period: Mapped[str] = mapped_column(String(32))
    period_end: Mapped[date | None] = mapped_column(Date)
    # True when facts for the same instrument/metric/period disagree; all of them are kept
    conflict: Mapped[bool] = mapped_column(Boolean, default=False, server_default=false())
    created_at = _now()


class RunLog(Base):
    __tablename__ = "run_log"
    id: Mapped[int] = mapped_column(primary_key=True)
    agent_id: Mapped[int | None] = mapped_column(ForeignKey("agents.id"))
    inputs: Mapped[Any] = mapped_column(JSON, nullable=True)
    prompts: Mapped[Any] = mapped_column(JSON, nullable=True)
    model_version: Mapped[str | None] = mapped_column(String(128))
    outputs: Mapped[Any] = mapped_column(JSON, nullable=True)
    run_id: Mapped[str | None] = mapped_column(String(128), index=True)
    role: Mapped[str | None] = mapped_column(String(32))
    prompt_tokens: Mapped[int | None] = mapped_column(Integer)
    completion_tokens: Mapped[int | None] = mapped_column(Integer)
    model_seconds: Mapped[float | None] = mapped_column(Float)
    created_at = _now()


class Analysis(Base):
    __tablename__ = "analyses"
    id: Mapped[int] = mapped_column(primary_key=True)
    instrument_id: Mapped[int] = mapped_column(ForeignKey("instruments.id"))
    agent_id: Mapped[int | None] = mapped_column(ForeignKey("agents.id"))
    run_log_id: Mapped[int | None] = mapped_column(ForeignKey("run_log.id"))
    kind: Mapped[str] = mapped_column(String(64))
    findings: Mapped[Any] = mapped_column(JSON, nullable=True)
    created_at = _now()


class Scorecard(Base):
    __tablename__ = "scorecards"
    __table_args__ = (
        UniqueConstraint("instrument_id", "run_date", name="uq_scorecard_instrument_run_date"),
        CheckConstraint("long_term_score BETWEEN 0 AND 100", name="ck_sc_long"),
        CheckConstraint("short_term_score BETWEEN 0 AND 100", name="ck_sc_short"),
        CheckConstraint("confidence IN ('low','medium','high')", name="ck_sc_conf"),
    )
    id: Mapped[int] = mapped_column(primary_key=True)
    instrument_id: Mapped[int] = mapped_column(ForeignKey("instruments.id"))
    run_date: Mapped[date] = mapped_column(Date)
    long_term_score: Mapped[float | None] = mapped_column(Float)
    short_term_score: Mapped[float | None] = mapped_column(Float)
    confidence: Mapped[str | None] = mapped_column(String(16))
    sub_scores: Mapped[Any] = mapped_column(JSON, nullable=True)
    benefits: Mapped[Any] = mapped_column(JSON, nullable=True)
    risks: Mapped[Any] = mapped_column(JSON, nullable=True)
    red_flags: Mapped[Any] = mapped_column(JSON, nullable=True)
    rules_version: Mapped[str | None] = mapped_column(String(32), nullable=True)
    created_at = _now()


class EvidenceLink(Base):
    __tablename__ = "evidence_links"
    __table_args__ = (
        CheckConstraint(
            "fact_id IS NOT NULL OR chunk_id IS NOT NULL", name="ck_evidence_fact_or_chunk"
        ),
    )
    id: Mapped[int] = mapped_column(primary_key=True)
    scorecard_id: Mapped[int | None] = mapped_column(ForeignKey("scorecards.id"))
    claim_type: Mapped[str] = mapped_column(String(32))  # benefit | risk | score
    claim_ref: Mapped[str | None] = mapped_column(String(128))
    fact_id: Mapped[int | None] = mapped_column(ForeignKey("facts.id"))
    chunk_id: Mapped[int | None] = mapped_column(ForeignKey("chunks.id"))
    source_id: Mapped[int | None] = mapped_column(ForeignKey("sources.id"))


class Agent(Base):
    __tablename__ = "agents"
    id: Mapped[int] = mapped_column(primary_key=True)
    tier: Mapped[int] = mapped_column(Integer)
    parent_id: Mapped[int | None] = mapped_column(ForeignKey("agents.id"))
    scope_instrument_id: Mapped[int | None] = mapped_column(ForeignKey("instruments.id"))
    scope_name: Mapped[str | None] = mapped_column(String(128))
    role: Mapped[str] = mapped_column(String(64))


class Job(Base):
    __tablename__ = "jobs"
    id: Mapped[int] = mapped_column(primary_key=True)
    agent_id: Mapped[int] = mapped_column(ForeignKey("agents.id"))
    trigger: Mapped[str] = mapped_column(String(32))
    status: Mapped[str] = mapped_column(String(16), default="queued", server_default="queued")
    attempts: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    scheduled_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    depends_on: Mapped[int | None] = mapped_column(ForeignKey("jobs.id"))
    # status: queued | running | done | failed (see ier.runtime.queue)
    claimed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_error: Mapped[str | None] = mapped_column(Text)
    payload: Mapped[Any] = mapped_column(JSON, nullable=True)


class AgentEvent(Base):
    __tablename__ = "agent_events"
    id: Mapped[int] = mapped_column(primary_key=True)
    agent_id: Mapped[int] = mapped_column(ForeignKey("agents.id"))
    kind: Mapped[str] = mapped_column(String(32))
    payload: Mapped[Any] = mapped_column(JSON, nullable=True)
    cost: Mapped[float] = mapped_column(Float, default=0, server_default="0")
    # clock_timestamp(), not now(): the INSERT time, not the transaction start, so the API's
    # settled watermark can trust it even for events written late in a long transaction
    created_at = mapped_column(DateTime(timezone=True), server_default=func.clock_timestamp())


class Signal(Base):
    __tablename__ = "signals"
    id: Mapped[int] = mapped_column(primary_key=True)
    instrument_id: Mapped[int] = mapped_column(ForeignKey("instruments.id"))
    rating: Mapped[str] = mapped_column(String(32))
    scorecard_id: Mapped[int | None] = mapped_column(ForeignKey("scorecards.id"))
    rules_version: Mapped[str] = mapped_column(String(32))
    run_date: Mapped[date] = mapped_column(Date)
    reasons: Mapped[Any] = mapped_column(JSON, nullable=True)  # plain-language list[str]


class SourceState(Base):
    """Latest connection status of one data source (config/sources.yaml). One row per source id."""
    __tablename__ = "source_state"
    source_id: Mapped[str] = mapped_column(String(64), primary_key=True)
    status: Mapped[str] = mapped_column(String(24))   # connected | needs_key | waiting_for_file | error | not_checked
    detail: Mapped[str | None] = mapped_column(Text)
    last_checked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_ok_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_count: Mapped[int | None] = mapped_column(Integer)   # points/files/items stored by the last good check
    latest: Mapped[Any] = mapped_column(JSON, nullable=True)  # small summary shown on the Sources page


class SeriesPoint(Base):
    """One dated value of a macro / market series (FX, rates, index levels, flows)."""
    __tablename__ = "series_points"
    series_id: Mapped[str] = mapped_column(String(64), primary_key=True)
    day: Mapped[date] = mapped_column(Date, primary_key=True)
    value: Mapped[float] = mapped_column(Float)
    source_id: Mapped[str] = mapped_column(String(64))


class AppendOnlyError(RuntimeError):
    """Raised on any attempt to update or delete an agent_events row."""


@event.listens_for(AgentEvent, "before_update")
def _agent_event_no_update(mapper, connection, target):
    raise AppendOnlyError("agent_events is append-only: UPDATE is not allowed")


@event.listens_for(AgentEvent, "before_delete")
def _agent_event_no_delete(mapper, connection, target):
    raise AppendOnlyError("agent_events is append-only: DELETE is not allowed")
